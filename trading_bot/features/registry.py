"""Feature registry.

Every feature is a function of a bar frame (one segment, index = bar open time) that returns a
Series aligned to it. The value at row t may use bars with index <= t only, i.e. data available
at the decision time t + tf (the bar's close). This is enforced generically by the truncation
test in ``tests/test_features.py``: every registered feature is recomputed on truncated history
and must be bit-identical on the overlapping rows.

Features are computed separately inside each data segment (see ``data.bars``), so no rolling
window ever spans a hole in the data; rows inside a feature's warm-up are NaN.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Iterable

import numpy as np
import pandas as pd


@dataclass(frozen=True)
class FeatureSpec:
    name: str
    family: str
    lookback: int  # bars of history, including the current bar, needed for a value
    description: str
    fn: Callable[[pd.DataFrame], pd.Series]
    available_at_time_t: bool = True


REGISTRY: dict[str, FeatureSpec] = {}


def register(name: str, family: str, lookback: int, description: str, fn: Callable[[pd.DataFrame], pd.Series],
             available_at_time_t: bool = True) -> None:
    if name in REGISTRY:
        raise ValueError(f"feature {name!r} registered twice")
    REGISTRY[name] = FeatureSpec(name, family, lookback, description, fn, available_at_time_t)


def _load_families() -> None:
    # Importing a family module registers its features.
    from trading_bot.features import microstructure, technical, volatility  # noqa: F401


def all_features() -> list[FeatureSpec]:
    _load_families()
    return list(REGISTRY.values())


def compute_features(bars: pd.DataFrame, names: Iterable[str] | None = None) -> pd.DataFrame:
    """Compute features per segment. Raises if any requested feature is not available at time t."""
    _load_families()
    specs = [REGISTRY[n] for n in names] if names is not None else list(REGISTRY.values())
    late = [s.name for s in specs if not s.available_at_time_t]
    if late:
        raise ValueError(f"features not available at decision time cannot be used: {late}")
    segments = bars.groupby("segment_id", sort=True) if "segment_id" in bars.columns else [(0, bars)]
    parts = []
    for _, seg in segments:
        parts.append(pd.DataFrame({s.name: s.fn(seg) for s in specs}, index=seg.index))
    out = pd.concat(parts).reindex(bars.index)
    return out.replace([np.inf, -np.inf], np.nan).astype(np.float64)


def registry_markdown() -> str:
    """Feature documentation table (docs/features.md is generated from this)."""
    lines = [
        "# Feature registry",
        "",
        "Generated by `python scripts/gen_feature_docs.py`; do not edit by hand.",
        "Windows are in bars of the dataset's timeframe. `available_at_time_t = TRUE` means the value at bar t",
        "uses only bars that have closed by the decision time (t + timeframe); the truncation test enforces it.",
        "",
        "| feature | family | lookback (bars) | available_at_time_t | description |",
        "|---|---|---|---|---|",
    ]
    for s in sorted(all_features(), key=lambda s: (s.family, s.name)):
        lines.append(f"| `{s.name}` | {s.family} | {s.lookback} | {'TRUE' if s.available_at_time_t else 'FALSE'} | {s.description} |")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------- shared helpers


def log_ret(b: pd.DataFrame) -> pd.Series:
    return np.log(b["close"]).diff()


def rolling_z(x: pd.Series, window: int, min_periods: int | None = None) -> pd.Series:
    r = x.rolling(window, min_periods=min_periods or window)
    return (x - r.mean()) / r.std()


def safe_div(a: pd.Series, b: pd.Series) -> pd.Series:
    return a / b.where(b != 0)
